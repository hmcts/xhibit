package uk.gov.courtservice.xhibit.client.results.pleas;

import java.awt.Dimension;
import java.awt.GridBagConstraints;
import java.awt.GridBagLayout;
import java.awt.Insets;
import java.awt.SystemColor;
import java.awt.event.ActionEvent;
import java.awt.event.ActionListener;
import java.util.Collection;
import java.util.Vector;

import javax.swing.BorderFactory;
import javax.swing.DefaultComboBoxModel;
import javax.swing.JComboBox;
import javax.swing.JLabel;
import javax.swing.JPanel;
import javax.swing.JTable;
import javax.swing.border.TitledBorder;

import uk.gov.courtservice.xhibit.client.util.XHIBITConstant;
import uk.gov.courtservice.xhibit.client.util.XHIBITErrorHandler;
import uk.gov.courtservice.xhibit.client.util.XhibitBundles;
import uk.gov.courtservice.xhibit.client.util.helpers.ResourceBundleHelper;
import uk.gov.courtservice.xhibit.client.util.table.renderers.TooltipComboBoxRenderer;

/**
 * <p>
 * Title: Plea Filter Panel
 * </p>
 * <p>
 * Description: Show Filter options panel for the PleaController screen. This
 * filter panel has 3 combo boxes that can filter indictments(charges), offences
 * and defendants. In this case the charges are Indictments and the offences are
 * Counts if hasCharges is true. Otherwise the offences are Summary Offences
 * (Section 41)
 * </p>
 * <p>
 * Copyright: Copyright (c) 2002
 * </p>
 * <p>
 * Company: EDS
 * </p>
 * 
 * @author Simon Gilmore
 * @version 1.0
 */
public class PleaFilterPanel extends JPanel {
    private PleaHelper ph = new PleaHelper();

    private GridBagLayout gridBagLayout1 = new GridBagLayout();

    private TitledBorder titledBorder1;

    private JComboBox indictmentCb = null;

    private JComboBox countCb = null;

    private JComboBox defendantCb = null;

    private JLabel indictmentLabel = null;

    private JLabel offenceLabel = null;

    private PleaControllerModel model = null;

    private PleaFilterSelectionModel pfs = null;

    private String comboSelectAll;

    private String indictmentFilter;

    private String countFilter;

    private String defendantFilter;

    private Integer indictment = new Integer(0);

    private Integer count = new Integer(0);

    private String chargeType;

    /** The table the filtering is going to be done on. */
    private JTable table;

    /**
     * Used when updating combo boxes using code to stop processing of the
     * events generated by the combo boxes.
     */
    private boolean ignoreEvents = false;

    /**
     * If true, shows the Charge filter option. Should be true for the instance
     * of this class used for the Indictment tab and false for the instance of
     * this class used for the Summary Offences tab of the PleaController
     * screen.
     */
    private boolean hasCharges = false;

    /**
     * Stores the original state of the Indictment filter before it is disabled
     */
    boolean isIndictmentSelectionAllowed = true;

    /** Stores the original state of the Count filter before it is disabled. */
    boolean isCountSelectionAlowed = false;

    /**
     * Stores the original state of the defendant filter before it is disabled.
     */
    boolean isDefendantSelectionAllowed = true;

    /**
     * Constructs a PleaFilterPanel.
     * 
     * @param pfs
     *            store the selected filter options.
     * @param model
     *            stores data retrieved by the PleaController.
     * @param hasCharges
     *            if true shows the Charge filter option.
     * @param table
     *            the table that this panel is going to filter.
     */
    public PleaFilterPanel(PleaFilterSelectionModel pfs, PleaControllerModel model, boolean hasCharges, JTable table) {
        try {
            this.pfs = pfs;
            this.model = model;
            this.hasCharges = hasCharges;
            comboSelectAll = ResourceBundleHelper.getResource(XhibitBundles.Pleas, "filter.combos.select.all");

            indictmentFilter = comboSelectAll;
            countFilter = comboSelectAll;
            defendantFilter = comboSelectAll;

            this.pfs.setIndictmentFilter(comboSelectAll);
            this.pfs.setCountFilter(comboSelectAll);
            this.pfs.setDefendmentFilter(comboSelectAll);
            this.table = table;

            if (hasCharges) {
                chargeType = PleaHelper.INDICTMENT_CHARGE_TYPE;
            } else {
                chargeType = PleaHelper.SECTION41_CHARGE_TYPE;
                indictment = PleaHelper.getSection41(model.getChargeCompositeValue());
                this.pfs.setIndictmentFilter(indictment.toString());
            }

            jbInit();
        } catch (Exception ex) {
            XHIBITErrorHandler.handleError(ex);
        }
    }

    /**
     * Create and layout the screen.
     */
    private void jbInit() {
        this.setLayout(gridBagLayout1);
        titledBorder1 = new TitledBorder(BorderFactory.createEtchedBorder(SystemColor.controlLtHighlight,
                SystemColor.controlShadow), ResourceBundleHelper
                .getResource(XhibitBundles.Pleas, "filter.border.title"));
        this.setBorder(titledBorder1);

        // If this panel has charges, i.e. it is being used for Indictments
        // get the indictment label and filter combo box.
        // (Summary Offences do not need the Charge label).
        if (hasCharges) {
            this.add(getIndictmentLabel(), new GridBagConstraints(0, 0, 1, 1, 0.0, 0.0, GridBagConstraints.WEST,
                    GridBagConstraints.NONE, new Insets(4, 4, 4, 4), 0, 0));
            this.add(getIndictmentCb(), new GridBagConstraints(1, 0, 1, 1, 0.0, 0.0, GridBagConstraints.WEST,
                    GridBagConstraints.NONE, new Insets(4, 4, 4, 4), 0, 0));
        }
        this.add(getOffenceLabel(), new GridBagConstraints(2, 0, 1, 1, 0.0, 0.0, GridBagConstraints.WEST,
                GridBagConstraints.NONE, new Insets(4, 4, 4, 4), 0, 0));
        this.add(getCountCb(), new GridBagConstraints(3, 0, 1, 1, 0.0, 0.0, GridBagConstraints.WEST,
                GridBagConstraints.NONE, new Insets(4, 4, 4, 4), 0, 0));

        this.add(new JLabel(ResourceBundleHelper.getResource(XhibitBundles.Pleas, "filter.label.defendant")),
                new GridBagConstraints(4, 0, 1, 1, 0.0, 0.0, GridBagConstraints.WEST, GridBagConstraints.NONE,
                        new Insets(4, 4, 4, 4), 0, 0));
        this.add(getDefendantCb(), new GridBagConstraints(5, 0, 1, 1, 0.0, 0.0, GridBagConstraints.WEST,
                GridBagConstraints.HORIZONTAL, new Insets(4, 4, 4, 4), 0, 0));
    }

    /**
     * Return the charge label, creating it if it does not already exist.
     * 
     * @return the Charge label.
     */
    private JLabel getIndictmentLabel() {
        if (indictmentLabel == null) {
            indictmentLabel = new JLabel(ResourceBundleHelper.getResource(XhibitBundles.Pleas,
                    "filter.label.indictment"));
        }
        return indictmentLabel;
    }

    /**
     * Return the Offence Label, creating it if it does not already exist. If
     * this panel has charges, i.e. Indictments, then get the Count text (as
     * offences on Indictments are known as Counts), otherwise get the offence
     * text.
     * 
     * @return the offence(or count) label.
     */
    private JLabel getOffenceLabel() {
        if (offenceLabel == null) {
            offenceLabel = new JLabel();
            if (hasCharges) {
                offenceLabel.setText(ResourceBundleHelper.getResource(XhibitBundles.Pleas, "filter.label.count"));
            } else {
                offenceLabel.setText(ResourceBundleHelper.getResource(XhibitBundles.Pleas, "filter.label.offence"));
            }
        }
        return offenceLabel;
    }

    /**
     * Creates, populates and returns the Indictment combo box.
     * 
     * @return the Indictment filter combo box.
     */
    protected JComboBox getIndictmentCb() {
        if (indictmentCb == null) {
            Collection c = pfs.getIndictments();
            indictmentCb = new JComboBox(getComboBoxModel(c));
            indictmentCb.setSelectedIndex(0);

            indictmentCb.addActionListener(new ActionListener() {
                public void actionPerformed(ActionEvent ie) {
                    indictmentCb_changed(ie);
                }
            });
        }
        return indictmentCb;
    }

    /**
     * Creates, populates and returns the Count combo box.
     * 
     * @return the Count filter combo box.
     */
    protected JComboBox getCountCb() {
        if (countCb == null) {
            Collection c = pfs.getCounts();
            countCb = new JComboBox(getComboBoxModel(c));

            if (c.size() != 0)
                countCb.setSelectedIndex(0);

            if (hasCharges) {
                countCb.setEnabled(false);
            }

            countCb.addActionListener(new ActionListener() {
                public void actionPerformed(ActionEvent ae) {
                    countCb_changed(ae);
                }
            });
        }
        return countCb;
    }

    /**
     * Creates, populates and returns the Defendant combo box.
     * 
     * @return the Defendant filter combo box.
     */
    protected JComboBox getDefendantCb() {
        if (defendantCb == null) {
            Collection c = pfs.getDefendants();
            defendantCb = new JComboBox(getComboBoxModel(c));
            defendantCb.setSelectedIndex(0);
            String[] tempArray = (String[]) c.toArray(new String[c.size()]);
            String[] tipList = new String[tempArray.length + 1];
            tipList[0] = "";
            System.arraycopy(tempArray, 0, tipList, 1, tempArray.length);
            TooltipComboBoxRenderer defRenderer = new TooltipComboBoxRenderer(tipList);
            defRenderer.setPreferredSize(new Dimension(250, XHIBITConstant.getLineHeight()));
            defRenderer.setMaximumSize(new Dimension(500, XHIBITConstant.getLineHeight()));
            defendantCb.setRenderer(defRenderer);
            defendantCb.addActionListener(new ActionListener() {
                public void actionPerformed(ActionEvent ae) {
                    defendantCb_changed(ae);
                }
            });
        }
        return defendantCb;
    }

    /**
     * Action performed when the Indictment combo box selection changes.
     * 
     * @param ae
     *            Semantic event which indicates that a component-defined action
     *            occured.
     */
    private void indictmentCb_changed(ActionEvent ae) {
        if (ignoreEvents)
            return;

        Collection colCounts;
        Collection colDefendants;

        table.clearSelection();

        Object selectedIndictment = getIndictmentCb().getSelectedItem();

        if (selectedIndictment instanceof Integer) {
            // A specific Indictment has been selected.
            indictment = (Integer) selectedIndictment;
            indictmentFilter = indictment.toString();

            // Get a unique collection of all the Counts for this
            // Indictment.
            colCounts = ph.getCountsOnIndictment(indictment, model.getChargeCompositeValue(), chargeType);

            // Get a unique collection of all the Defendants for this
            // Indictment.
            colDefendants = ph.getDefendantsOnIndictment(indictment, model.getChargeCompositeValue(), chargeType);

            getCountCb().setEnabled(true);
        } else {
            // All Indictments has been selected.
            indictmentFilter = (String) selectedIndictment;

            // Get a unique collection of all the Count numbers.
            colCounts = ph.getAllCounts(model.getChargeCompositeValue(), chargeType);

            // Get a unique collection of all the Defendant names.
            colDefendants = ph.getAllDefendants(model.getChargeCompositeValue(), chargeType);

            // Being able to select Counts across all Indictments does not
            // make
            // sense, so disable the Count filter combo box.
            getCountCb().setEnabled(false);
        }

        // The Indictment filter has changed, so the defendants have probably
        // changed, so set the defendant filter to All.
        countFilter = comboSelectAll;
        defendantFilter = comboSelectAll;

        ignoreEvents = true;

        // reload the Count filter combo box.
        getCountCb().setModel(getComboBoxModel(colCounts));
        getCountCb().setSelectedIndex(0);

        // reload the Defendant filter combo box.
        getDefendantCb().setModel(getComboBoxModel(colDefendants));
        getDefendantCb().setSelectedIndex(0);

        ignoreEvents = false;

        setFilterPleas();
        pfs.setIndictmentFilter(indictmentFilter);
    }

    /**
     * Action performed when the Count filter combo box selection changes.
     * 
     * @param ae
     *            Semantic event which indicates that a component-defined action
     *            occured.
     */
    private void countCb_changed(ActionEvent ae) {
        if (ignoreEvents)
            return;

        Collection colDefendants;

        if (!hasCharges)
            table.clearSelection();

        Object selectedCount = getCountCb().getSelectedItem();
        if (selectedCount instanceof Integer) {
            // A specific Count has been selected.
            count = (Integer) selectedCount;
            countFilter = count.toString();

            // Get the Defendants on this Count.
            colDefendants = ph.getDefendantsOnCount(indictment, count, model.getChargeCompositeValue(), chargeType);
        } else {
            // All (Counts) has been selected (therefore the whole
            // Indictment
            // has been selected).
            countFilter = (String) selectedCount;

            // Get the unique collection of Defendant names on this
            // Indictment.
            colDefendants = ph.getDefendantsOnIndictment(indictment, model.getChargeCompositeValue(), chargeType);
        }

        // The Count filter has changed, so the defendants have probably
        // changed, so set the defendant filter to All.
        defendantFilter = comboSelectAll;

        ignoreEvents = true;

        // Reload the Defendant filter combo box.
        getDefendantCb().setModel(getComboBoxModel(colDefendants));
        getDefendantCb().setSelectedIndex(0);

        ignoreEvents = false;

        setFilterPleas();
        pfs.setCountFilter(countFilter);
    }

    /**
     * Action performed when the Defendant filter combo box selection changes.
     * 
     * @param ae
     *            Semantic event which indicates that a component-defined action
     *            occured.
     */
    private void defendantCb_changed(ActionEvent ae) {
        if (ignoreEvents)
            return;

        defendantFilter = (String) getDefendantCb().getSelectedItem();
        setFilterPleas();
        pfs.setDefendmentFilter(defendantFilter);
    }

    /**
     * Creates a DefaultComboBoxModel with a "select all" at index zero followed
     * by all of the elements of the collection c.
     * 
     * @param c
     *            collection to put into a DefaultComboBoxModel
     * @return the populated DefaultComboBoxModel.
     */
    private DefaultComboBoxModel getComboBoxModel(Collection c) {
        Vector v = new Vector();
        v.add(comboSelectAll);
        v.addAll(c);
        return new DefaultComboBoxModel(v);
    }

    /**
     * Sets the filter that will be applied to the table, based on the
     * Indictment(charge), offence(count) and defendant filters.
     */
    private void setFilterPleas() {
        if (indictmentFilter.equals(comboSelectAll)) {
            if (countFilter.equals(comboSelectAll)) {
                if (defendantFilter.equals(comboSelectAll)) {
                    pfs.setFilter(PleaFilterSelectionModel.FILTER_NONE);
                } else {
                    pfs.setFilter(PleaFilterSelectionModel.FILTER_DEFENDANT);
                }
            } else {
                // Can only get here when hasCharges is false, i.e. for
                // Summary Offences (Section 41s) tab.
                if (defendantFilter.equals(comboSelectAll)) {
                    pfs.setFilter(PleaFilterSelectionModel.FILTER_COUNT);
                } else {
                    pfs.setFilter(PleaFilterSelectionModel.FILTER_INDICTMENT_COUNT_DEFENDANT);
                }
            }
        } else {
            if (countFilter.equals(comboSelectAll)) {
                if (defendantFilter.equals(comboSelectAll)) {
                    pfs.setFilter(PleaFilterSelectionModel.FILTER_INDICTMENT);
                } else {
                    pfs.setFilter(PleaFilterSelectionModel.FILTER_INDICTMENT_DEFENDANT);
                }
            } else {
                if (defendantFilter.equals(comboSelectAll)) {
                    pfs.setFilter(PleaFilterSelectionModel.FILTER_INDICTMENT_COUNT);
                } else {
                    pfs.setFilter(PleaFilterSelectionModel.FILTER_INDICTMENT_COUNT_DEFENDANT);
                }
            }
        }
    }

    /**
     * Disables the filters, saving their current state first.
     */
    public void disableFilters() {
        isIndictmentSelectionAllowed = getIndictmentCb().isEnabled();
        isCountSelectionAlowed = getCountCb().isEnabled();
        isDefendantSelectionAllowed = getDefendantCb().isEnabled();

        getIndictmentCb().setEnabled(false);
        getCountCb().setEnabled(false);
        getDefendantCb().setEnabled(false);
    }

    /**
     * Restores the filters to the state they had before they were all disabled.
     */
    public void restoreFilters() {
        getIndictmentCb().setEnabled(isIndictmentSelectionAllowed);
        getCountCb().setEnabled(isCountSelectionAlowed);
        getDefendantCb().setEnabled(isDefendantSelectionAllowed);
    }
}