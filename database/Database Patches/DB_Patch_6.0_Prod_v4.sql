DECLARE

  l_max_display_id          NUMBER;
  l_max_rotation_set_id     NUMBER;
  l_max_display_document_id NUMBER;
  l_max_display_type_id     NUMBER;
  l_max_display_location_id NUMBER;
  l_max_rotation_set_dd_id  NUMBER;

  l_new_display_id          NUMBER;
  l_new_rotation_set_id     NUMBER;
  l_new_display_document_id NUMBER;
  l_new_display_type_id     NUMBER;
  l_new_display_location_id NUMBER;
  l_new_rotation_set_dd_id  NUMBER;

  l_display_id          NUMBER;
  l_rotation_set_id     NUMBER;
  l_display_document_id NUMBER;
  l_display_type_id     NUMBER;
  l_display_location_id NUMBER;
  l_rotation_set_dd_id  NUMBER;

  l_stmt      VARCHAR2(500);

  CURSOR c_display_type IS
    SELECT display_type_id
    FROM   xhb_display_type
    WHERE  display_type_id < 0
    ORDER BY display_type_id;

  CURSOR c_display_location IS
    SELECT display_location_id
    FROM   xhb_display_location
    WHERE  display_location_id < 0
    ORDER BY display_location_id;

  CURSOR c_display_document IS
    SELECT display_document_id
    FROM   xhb_display_document
    WHERE  display_document_id < 0
    ORDER BY display_document_id;

  CURSOR c_rotation_sets IS
    SELECT rotation_set_id
    FROM   xhb_rotation_sets
    WHERE  rotation_set_id < 0
    ORDER BY rotation_set_id;

  CURSOR c_rotation_set_dd IS
    SELECT rotation_set_dd_id
    FROM   xhb_rotation_set_dd
    WHERE  rotation_set_dd_id < 0
    ORDER BY rotation_set_dd_id;

  CURSOR c_display IS
    SELECT display_id
    FROM   xhb_display
    WHERE  display_id < 0
    ORDER BY display_id;

  CURSOR c_max_display_id IS
    SELECT max(display_id)
    FROM   xhb_display;

  CURSOR c_max_display_type_id IS
    SELECT max(display_type_id)
    FROM   xhb_display_type;

  CURSOR c_max_display_location_id IS
    SELECT max(display_location_id)
    FROM   xhb_display_location;

  CURSOR c_max_rotation_set_id IS
    SELECT max(rotation_set_id)
    FROM   xhb_rotation_sets;

  CURSOR c_max_rotation_set_dd_id IS
    SELECT max(rotation_set_dd_id)
    FROM   xhb_rotation_set_dd;

  CURSOR c_max_display_document_id IS
    SELECT max(display_document_id)
    FROM   xhb_display_document;

BEGIN

  /*
   * Disable FKs to allow update of data
   */

  l_stmt := 'ALTER TABLE XHB_DISPLAY DISABLE CONSTRAINT DISPLAY_DISPLAY_LOCATION_ID_FK';
  EXECUTE IMMEDIATE l_stmt;
  l_stmt := 'ALTER TABLE XHB_DISPLAY DISABLE CONSTRAINT DISPLAY_DISPLAY_TYPE_ID_FK';
  EXECUTE IMMEDIATE l_stmt;
  l_stmt := 'ALTER TABLE XHB_DISPLAY DISABLE CONSTRAINT DISPLAY_ROTATION_SET_ID_FK';
  EXECUTE IMMEDIATE l_stmt;
  l_stmt := 'ALTER TABLE XHB_DISPLAY_COURT_ROOM DISABLE CONSTRAINT DISPLAY_COURT_RM_DISPLAY_ID_FK';
  EXECUTE IMMEDIATE l_stmt;
  l_stmt := 'ALTER TABLE XHB_ROTATION_SET_DD DISABLE CONSTRAINT ROT_SET_DD_ROTATION_SET_ID_FK';
  EXECUTE IMMEDIATE l_stmt;
  l_stmt := 'ALTER TABLE XHB_ROTATION_SET_DD DISABLE CONSTRAINT ROT_SET_DD_DISPLAY_DOC_ID_FK';
  EXECUTE IMMEDIATE l_stmt;


  /*
   * Start from 'bottom' up for clarity (although FKs disabled)
   */

  -- XHB_DISPLAY to XHB_DISPLAY_COURT_ROOM


  OPEN c_max_display_id;
  LOOP

    FETCH c_max_display_id
    INTO  l_max_display_id;

    EXIT WHEN c_max_display_id%NOTFOUND;

  END LOOP;
  CLOSE c_max_display_id;

  l_new_display_id := l_max_display_id + 1;

  OPEN c_display;

  LOOP

    FETCH c_display
    INTO  l_display_id;

    EXIT WHEN c_display%NOTFOUND;

    UPDATE xhb_display_court_room
    SET    display_id = l_new_display_id
    WHERE  display_id = l_display_id;

    UPDATE xhb_display
    SET    display_id = l_new_display_id
    WHERE  display_id = l_display_id;

    l_new_display_id := l_new_display_id + 1;

  END LOOP;

  CLOSE c_display;

  l_new_display_id := l_new_display_id + 1;

  l_stmt := 'DROP SEQUENCE XHB_DISPLAY_SEQ';
  EXECUTE IMMEDIATE l_stmt;

  l_stmt := 'CREATE SEQUENCE XHB_DISPLAY_SEQ START WITH '||l_new_display_id||' MAXVALUE 999999999999999999 MINVALUE 1 NOCACHE NOCYCLE NOORDER';
  EXECUTE IMMEDIATE l_stmt;

  -- XHB_DISPLAY_TYPE to XHB_DISPLAY

  OPEN c_max_display_type_id;
  LOOP

    FETCH c_max_display_type_id
    INTO  l_max_display_type_id;

    EXIT WHEN c_max_display_type_id%NOTFOUND;

  END LOOP;
  CLOSE c_max_display_type_id;

  l_new_display_type_id := l_max_display_type_id + 1;

  OPEN c_display_type;

  LOOP

    FETCH c_display_type
    INTO  l_display_type_id;

    EXIT WHEN c_display_type%NOTFOUND;

    UPDATE xhb_display
    SET    display_type_id = l_new_display_type_id
    WHERE  display_type_id = l_display_type_id;

    UPDATE xhb_display_type
    SET    display_type_id = l_new_display_type_id
    WHERE  display_type_id = l_display_type_id;

    l_new_display_type_id := l_new_display_type_id + 1;

  END LOOP;

  CLOSE c_display_type;

  l_new_display_type_id := l_new_display_type_id + 1;

  l_stmt := 'DROP SEQUENCE XHB_DISPLAY_TYPE_SEQ';
  EXECUTE IMMEDIATE l_stmt;

  l_stmt := 'CREATE SEQUENCE XHB_DISPLAY_TYPE_SEQ START WITH '||l_new_display_type_id||' MAXVALUE 999999999999999999 MINVALUE 1 NOCACHE NOCYCLE NOORDER';
  EXECUTE IMMEDIATE l_stmt;


  -- XHB_DISPLAY_LOCATION to XHB_DISPLAY

  OPEN c_max_display_location_id;
  LOOP

    FETCH c_max_display_location_id
    INTO  l_max_display_location_id;

    EXIT WHEN c_max_display_location_id%NOTFOUND;

  END LOOP;
  CLOSE c_max_display_location_id;

  l_new_display_location_id := l_max_display_location_id + 1;

  OPEN c_display_location;

  LOOP

    FETCH c_display_location
    INTO  l_display_location_id;

    EXIT WHEN c_display_location%NOTFOUND;

    UPDATE xhb_display
    SET    display_location_id = l_new_display_location_id
    WHERE  display_location_id = l_display_location_id;

    UPDATE xhb_display_location
    SET    display_location_id = l_new_display_location_id
    WHERE  display_location_id = l_display_location_id;

    l_new_display_location_id := l_new_display_location_id + 1;

  END LOOP;

  CLOSE c_display_location;

  l_new_display_location_id := l_new_display_location_id + 1;

  l_stmt := 'DROP SEQUENCE XHB_DISPLAY_LOCATION_SEQ';
  EXECUTE IMMEDIATE l_stmt;

  l_stmt := 'CREATE SEQUENCE XHB_DISPLAY_LOCATION_SEQ START WITH '||l_new_display_location_id||' MAXVALUE 999999999999999999 MINVALUE 1 NOCACHE NOCYCLE NOORDER';
  EXECUTE IMMEDIATE l_stmt;

  -- XHB_ROTATION_SETS to XHB_DISPLAY and XHB_ROTATION_SET_DD

  OPEN c_max_rotation_set_id;
  LOOP

    FETCH c_max_rotation_set_id
    INTO  l_max_rotation_set_id;

    EXIT WHEN c_max_rotation_set_id%NOTFOUND;

  END LOOP;
  CLOSE c_max_rotation_set_id;

  l_new_rotation_set_id := l_max_rotation_set_id + 1;

  OPEN c_rotation_sets;

  LOOP

    FETCH c_rotation_sets
    INTO  l_rotation_set_id;

    EXIT WHEN c_rotation_sets%NOTFOUND;

    UPDATE xhb_display
    SET    rotation_set_id = l_new_rotation_set_id
    WHERE  rotation_set_id = l_rotation_set_id;

    UPDATE xhb_rotation_set_dd
    SET    rotation_set_id = l_new_rotation_set_id
    WHERE  rotation_set_id = l_rotation_set_id;

    UPDATE xhb_rotation_sets
    SET    rotation_set_id = l_new_rotation_set_id
    WHERE  rotation_set_id = l_rotation_set_id;

    l_new_rotation_set_id := l_new_rotation_set_id + 1;

  END LOOP;

  CLOSE c_rotation_sets;

  l_new_rotation_set_id := l_new_rotation_set_id + 1;

  l_stmt := 'DROP SEQUENCE XHB_ROTATION_SETS_SEQ';
  EXECUTE IMMEDIATE l_stmt;

  l_stmt := 'CREATE SEQUENCE XHB_ROTATION_SETS_SEQ START WITH '||l_new_rotation_set_id||' MAXVALUE 999999999999999999 MINVALUE 1 NOCACHE NOCYCLE NOORDER';
  EXECUTE IMMEDIATE l_stmt;

  -- XHB_DISPLAY_DOCUMENT to XHB_ROTATION_SET_DD

  OPEN c_max_display_document_id;
  LOOP

    FETCH c_max_display_document_id
    INTO  l_max_display_document_id;

    EXIT WHEN c_max_display_document_id%NOTFOUND;

  END LOOP;
  CLOSE c_max_display_document_id;

  l_new_display_document_id := l_max_display_document_id + 1;

  OPEN c_display_document;

  LOOP

    FETCH c_display_document
    INTO  l_display_document_id;

    EXIT WHEN c_display_document%NOTFOUND;

    UPDATE xhb_rotation_set_dd
    SET    display_document_id = l_new_display_document_id
    WHERE  display_document_id = l_display_document_id;

    UPDATE xhb_display_document
    SET    display_document_id = l_new_display_document_id
    WHERE  display_document_id = l_display_document_id;

    l_new_display_document_id := l_new_display_document_id + 1;

  END LOOP;

  CLOSE c_display_document;

  l_new_display_document_id := l_new_display_document_id + 1;

  l_stmt := 'DROP SEQUENCE XHB_DISPLAY_DOCUMENT_SEQ';
  EXECUTE IMMEDIATE l_stmt;

  l_stmt := 'CREATE SEQUENCE XHB_DISPLAY_DOCUMENT_SEQ START WITH '||l_new_display_document_id||' MAXVALUE 999999999999999999 MINVALUE 1 NOCACHE NOCYCLE NOORDER';
  EXECUTE IMMEDIATE l_stmt;

  OPEN c_max_rotation_set_dd_id;
  LOOP

    FETCH c_max_rotation_set_dd_id
    INTO  l_max_rotation_set_dd_id;

    EXIT WHEN c_max_rotation_set_dd_id%NOTFOUND;

  END LOOP;
  CLOSE c_max_rotation_set_dd_id;

  l_new_rotation_set_dd_id := l_max_rotation_set_dd_id + 1;

  OPEN c_rotation_set_dd;

  LOOP

    FETCH c_rotation_set_dd
    INTO  l_rotation_set_dd_id;

    EXIT WHEN c_rotation_set_dd%NOTFOUND;

    UPDATE xhb_rotation_set_dd
    SET    rotation_set_dd_id = l_new_rotation_set_dd_id
    WHERE  rotation_set_dd_id = l_rotation_set_dd_id;

    l_new_rotation_set_dd_id := l_new_rotation_set_dd_id + 1;

  END LOOP;

  CLOSE c_rotation_set_dd;

  l_new_rotation_set_dd_id := l_new_rotation_set_dd_id + 1;

  l_stmt := 'DROP SEQUENCE XHB_ROTATION_SET_DD_SEQ';
  EXECUTE IMMEDIATE l_stmt;

  l_stmt := 'CREATE SEQUENCE XHB_ROTATION_SET_DD_SEQ START WITH '||l_new_rotation_set_dd_id||' MAXVALUE 999999999999999999 MINVALUE 1 NOCACHE NOCYCLE NOORDER';
  EXECUTE IMMEDIATE l_stmt;

  l_stmt := 'ALTER TABLE XHB_DISPLAY ENABLE CONSTRAINT DISPLAY_DISPLAY_LOCATION_ID_FK';
  EXECUTE IMMEDIATE l_stmt;
  l_stmt := 'ALTER TABLE XHB_DISPLAY ENABLE CONSTRAINT DISPLAY_DISPLAY_TYPE_ID_FK';
  EXECUTE IMMEDIATE l_stmt;
  l_stmt := 'ALTER TABLE XHB_DISPLAY ENABLE CONSTRAINT DISPLAY_ROTATION_SET_ID_FK';
  EXECUTE IMMEDIATE l_stmt;
  l_stmt := 'ALTER TABLE XHB_DISPLAY_COURT_ROOM ENABLE CONSTRAINT DISPLAY_COURT_RM_DISPLAY_ID_FK';
  EXECUTE IMMEDIATE l_stmt;
  l_stmt := 'ALTER TABLE XHB_ROTATION_SET_DD ENABLE CONSTRAINT ROT_SET_DD_ROTATION_SET_ID_FK';
  EXECUTE IMMEDIATE l_stmt;
  l_stmt := 'ALTER TABLE XHB_ROTATION_SET_DD ENABLE CONSTRAINT ROT_SET_DD_DISPLAY_DOC_ID_FK';
  EXECUTE IMMEDIATE l_stmt;

END;
