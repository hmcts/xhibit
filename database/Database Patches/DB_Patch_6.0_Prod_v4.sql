/*
 * SPECIAL CASE for this release - renaming all the FKs for ease of management
 * and future change.  Do at start to make Forms B-F changes easier!!
 */

DECLARE

  l_stmt      VARCHAR2(500);
  l_fk_table  VARCHAR2(100);
  l_fk_const  VARCHAR2(100);

  CURSOR c_foriegn_keys IS
    SELECT table_name,
           constraint_name
    FROM   user_constraints
    WHERE  table_name LIKE 'XHB_%'
    AND    constraint_type = 'R';

BEGIN

  /*
   * Remove the Foriegn Keys
   */

  OPEN c_foriegn_keys;

  LOOP

    FETCH c_foriegn_keys
    INTO  l_fk_table,
          l_fk_const;

    EXIT WHEN c_foriegn_keys%NOTFOUND;

    l_stmt := 'ALTER TABLE '||l_fk_table||' DROP CONSTRAINT '||l_fk_const;

    EXECUTE IMMEDIATE l_stmt;

  END LOOP;

  CLOSE c_foriegn_keys;

END;
