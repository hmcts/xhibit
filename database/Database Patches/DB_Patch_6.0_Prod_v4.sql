        --log_entry('get_court_room');
    
        OPEN p_results_out FOR
            SELECT DISTINCT cr.court_room_id AS "id",
                   t.location AS location,
                   cr.*
            FROM   XHB_COURT_ROOM cr,
                   XHB_COURT_SITE cs,
                   XHB_COURT c,
                   XHB_TERMINAL t
            WHERE  cr.court_site_id = cs.court_site_id
